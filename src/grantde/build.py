"""Generate the GrantDE static site; use --preview for a local draft catalogue."""

import argparse
import gzip
import hashlib
import json
import math
import shutil
import sys
from datetime import date
from html.parser import HTMLParser
from pathlib import Path
from tempfile import TemporaryDirectory
from urllib.parse import urlsplit

from jinja2 import Environment, FileSystemLoader, StrictUndefined, TemplateError, select_autoescape

from .catalogue import CatalogueError, load_catalogue, read_json, write_json
from .presentation import LABELS, date_label, label, public_record, round_view
from .validate import _valid_url, require_valid


PAGE_SIZE = 12
BUILD_MARKER = ".grantde-build.json"


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links, self.ids = [], set()

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        if "id" in attrs:
            self.ids.add(attrs["id"])
        for key in ("href", "src"):
            if attrs.get(key):
                self.links.append(attrs[key])


def check_internal_links(output: Path) -> None:
    pages = {}
    for path in output.rglob("*.html"):
        parser = Links()
        parser.feed(path.read_text(encoding="utf-8"))
        pages[path] = parser
    for path, page in pages.items():
        for link in page.links:
            parsed = urlsplit(link)
            if parsed.scheme or parsed.netloc:
                continue
            target = output / parsed.path.lstrip("/") if parsed.path.startswith("/") else path.parent / parsed.path
            target = target.resolve()
            if not target.is_relative_to(output.resolve()):
                raise CatalogueError(f"{path.name}: internal link escapes the generated site: {link}")
            if target.is_dir():
                target /= "index.html"
            if not target.is_file():
                raise CatalogueError(f"{path.relative_to(output)}: missing internal link {link}")
            if parsed.fragment and target in pages and parsed.fragment not in pages[target].ids:
                raise CatalogueError(f"{path.relative_to(output)}: missing anchor {link}")


def directory_url(page: int) -> str:
    return "/scholarships/" if page == 1 else f"/scholarships/page/{page}/"


def _check_output(root: Path, output: Path, preview: bool) -> None:
    build_root = root / "build"
    allowed = output.is_relative_to(build_root) and output != build_root
    if not preview:
        allowed = allowed or output == root / "dist"
    if not allowed:
        raise CatalogueError("preview output must be inside build/; public output must be dist/ or inside build/")
    if output.exists() and not output.is_dir():
        raise CatalogueError(f"{output}: output is not a directory")
    if output.exists() and any(output.iterdir()):
        marker = output / BUILD_MARKER
        if not marker.is_file() or read_json(marker).get("generator") != "grantde":
            raise CatalogueError(f"{output}: refusing to replace a directory not generated by GrantDE")


def build_site(root: Path, data_dir: Path, output: Path, *, preview=False, today=None) -> dict:
    root, output = root.resolve(), output.resolve()
    _check_output(root, output, preview)
    today = today or date.today()
    catalogue = load_catalogue(data_dir)
    require_valid(catalogue)
    config_path = root / "site.json"
    config = read_json(config_path if config_path.is_file() else root / "site.example.json")
    selected = [record for _, record in catalogue.records if record["publication"]["status"] == "published"
                or (preview and record["publication"]["status"] == "draft")]
    if not preview:
        if not selected:
            raise CatalogueError("No published scholarships. Use --preview for local development with draft records.")
        missing = [key for key in ("base_url", "corrections_url", "operator_name", "operator_address", "operator_email")
                   if not config.get(key)]
        if missing:
            raise CatalogueError(f"Public launch configuration is incomplete in site.json: {', '.join(missing)}")
        for key in ("base_url", "corrections_url"):
            if not _valid_url(config[key]):
                raise CatalogueError(f"site.json/{key}: expected an absolute HTTP(S) URL")
    selected.sort(key=lambda record: (record["title"].casefold(), record["id"]))
    cards = [public_record(record, today) for record in selected]
    compact_index = json.dumps(cards, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    fingerprint = hashlib.sha256(compact_index.encode()).hexdigest()[:12]
    environment = Environment(
        loader=FileSystemLoader(root / "templates"), autoescape=select_autoescape(["html", "xml"]),
        undefined=StrictUndefined, trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True,
    )
    environment.filters.update(label=label, date_label=date_label)
    total_pages = max(1, math.ceil(len(cards) / PAGE_SIZE))
    asset_hash = hashlib.sha256()
    for path in sorted((root / "static").rglob("*")):
        if path.is_file():
            asset_hash.update(path.relative_to(root / "static").as_posix().encode() + b"\0")
            asset_hash.update(path.read_bytes())
    asset_directory = Path("assets") / asset_hash.hexdigest()[:12]
    common = {
        "config": config, "preview": preview, "total": len(cards), "as_of": today.isoformat(),
        "collected_on": catalogue.manifest["collected_on"], "labels": LABELS,
        "vocabularies": catalogue.vocabularies, "directory_url": directory_url,
        "index_url": f"/assets/catalogue.{fingerprint}.json", "fingerprint": fingerprint,
        "assets_url": f"/{asset_directory.as_posix()}",
        "page_size": PAGE_SIZE, "source_count": len(catalogue.sources),
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix=".grantde-site-", dir=output.parent) as temporary:
        staging = Path(temporary) / "site"
        staging.mkdir()
        routes = []

        def render(template, route, **context):
            destination = staging / (route.lstrip("/") + "index.html" if route.endswith("/") else route.lstrip("/"))
            destination.parent.mkdir(parents=True, exist_ok=True)
            html = environment.get_template(template).render(**common, route=route, **context)
            destination.write_text(html, encoding="utf-8", newline="\n")
            if route != "/404.html":
                routes.append(route)

        featured_ids = ["daad-50026200", "daad-10000113", "berlin-elsa-neumann-doctoral-scholarship"]
        featured = sorted(cards, key=lambda card: (
            featured_ids.index(card["id"]) if card["id"] in featured_ids else len(featured_ids), card["title"]
        ))[:3]
        render("home.html", "/", title="Scholarships for your next chapter", featured=featured)
        for page in range(1, total_pages + 1):
            start = (page - 1) * PAGE_SIZE
            render("directory.html", directory_url(page), title="Scholarship directory", cards=cards[start:start + PAGE_SIZE],
                   page=page, total_pages=total_pages, start=start + 1, end=min(start + PAGE_SIZE, len(cards)))
        for record, card in zip(selected, cards):
            render("scholarship.html", card["url"], title=record["title"], record=record, card=card,
                   rounds=[{**round_, **round_view(round_, today)} for round_ in record["application_rounds"]])
        for name, title in (("about", "About & coverage"), ("contact", "Contact & corrections"),
                            ("privacy", "Privacy"), ("legal", "Operator information")):
            render("information.html", f"/{name}/", title=title, section=name)
        render("not_found.html", "/404.html", title="Page not found")
        asset_output = staging / asset_directory
        shutil.copytree(root / "static", asset_output)
        (staging / common["index_url"].lstrip("/")).write_text(compact_index, encoding="utf-8", newline="\n")
        robots = "User-agent: *\nDisallow: /\n" if preview else f"User-agent: *\nAllow: /\nSitemap: {config['base_url'].rstrip('/')}/sitemap.xml\n"
        (staging / "robots.txt").write_text(robots, encoding="utf-8", newline="\n")
        if not preview:
            xml = environment.get_template("sitemap.xml").render(base_url=config["base_url"].rstrip("/"), routes=routes)
            (staging / "sitemap.xml").write_text(xml, encoding="utf-8", newline="\n")
        (staging / "_headers").write_text(
            "/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n"
            "  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self'; font-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'\n"
            + ("  X-Robots-Tag: noindex, nofollow\n" if preview else ""), encoding="utf-8", newline="\n",
        )
        metrics = {"pages": len(list(staging.rglob("*.html"))), "records": len(cards),
                   "css_gzip_bytes": len(gzip.compress((asset_output / "css/site.css").read_bytes(), mtime=0)),
                   "js_gzip_bytes": sum(len(gzip.compress(p.read_bytes(), mtime=0))
                                        for p in (asset_output / "js").iterdir() if p.suffix in {".js", ".mjs"}),
                   "index_bytes": len(compact_index.encode()),
                   "index_gzip_bytes": len(gzip.compress(compact_index.encode(), mtime=0))}
        write_json(staging / BUILD_MARKER, {"generator": "grantde", "preview": preview, "as_of": today.isoformat(), **metrics})
        check_internal_links(staging)
        # Only a resolved, owned output under build/ or dist/ can reach this replacement.
        _check_output(root, output, preview)
        if output.exists():
            shutil.rmtree(output)
        staging.rename(output)
    return metrics


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-dir", type=Path, default=Path("."))
    parser.add_argument("--data-dir", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--preview", action="store_true", help="include drafts in a clearly marked local build under build/")
    parser.add_argument("--as-of", type=date.fromisoformat, default=None, help="use an explicit date (YYYY-MM-DD)")
    args = parser.parse_args(argv)
    root = args.project_dir.resolve()
    output = args.output or root / ("build/preview" if args.preview else "dist")
    try:
        metrics = build_site(root, args.data_dir or root / "data", output, preview=args.preview, today=args.as_of)
    except (CatalogueError, OSError, TemplateError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    mode = "Local draft preview" if args.preview else "Published catalogue"
    print(f"{mode}: {metrics['records']} scholarships, {metrics['pages']} pages -> {output}")
    print(f"Gzip sizes: CSS {metrics['css_gzip_bytes']} B; JS {metrics['js_gzip_bytes']} B; index {metrics['index_gzip_bytes']} B.")
    if args.preview:
        print(f'Preview: python -m http.server 8000 --bind 127.0.0.1 --directory "{output}"')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
